"""Persistence for SRS cards, in the reader's own schema."""
from __future__ import annotations


from state import ensure, open_state
from datetime import datetime

from srs.card import Card
from vocab.entry import Unit

SCHEMA = """
CREATE TABLE IF NOT EXISTS cards (
    card_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          TEXT COLLATE "C" NOT NULL,
    key           TEXT COLLATE "C" NOT NULL,
    due_date      TEXT COLLATE "C" NOT NULL,
    interval_days DOUBLE PRECISION NOT NULL,
    ease_factor   DOUBLE PRECISION NOT NULL,
    repetitions   BIGINT NOT NULL,
    last_review   TEXT COLLATE "C",
    lapses        BIGINT NOT NULL DEFAULT 0,
    UNIQUE (kind, key)
);
CREATE INDEX IF NOT EXISTS ix_cards_due ON cards(due_date);
"""


class CardStore:
    def __init__(self, config) -> None:
        self._db = config
        ensure(config, SCHEMA)

    def add(self, card: Card) -> None:
        """Insert a card, leaving an existing one for the same unit alone —
        a claim made twice is one claim, with its history."""
        with open_state(self._db) as conn:
            conn.execute(
                "INSERT INTO cards"
                " (kind, key, due_date, interval_days, ease_factor, repetitions,"
                "  last_review, lapses) VALUES (%s, %s, %s, %s, %s, %s, %s, %s)"
                " ON CONFLICT DO NOTHING",
                self._to_row(card),
            )

    def add_many(self, cards: list[Card]) -> None:
        """Insert many cards in one transaction.

        `add` commits per call, which is a connection and an fsync each. A
        roadmap mints one card per step, so at eighteen thousand steps that
        alone outweighs the walk that produced them.
        """
        if not cards:
            return
        with open_state(self._db) as conn:
            conn.executemany(
                "INSERT INTO cards"
                " (kind, key, due_date, interval_days, ease_factor, repetitions,"
                "  last_review, lapses) VALUES (%s, %s, %s, %s, %s, %s, %s, %s)"
                " ON CONFLICT DO NOTHING",
                [self._to_row(card) for card in cards],
            )

    def save(self, card: Card) -> None:
        with open_state(self._db) as conn:
            conn.execute(
                "UPDATE cards SET due_date = %s, interval_days = %s, ease_factor = %s,"
                " repetitions = %s, last_review = %s, lapses = %s WHERE kind = %s AND key = %s",
                (card.due_date.isoformat(), card.interval_days, card.ease_factor,
                 card.repetitions,
                 card.last_review.isoformat() if card.last_review else None,
                 card.lapses, card.unit.kind, card.unit.key),
            )

    def remove(self, unit: Unit) -> None:
        """Drop a unit's card: the claim graduated, or was withdrawn."""
        with open_state(self._db) as conn:
            conn.execute("DELETE FROM cards WHERE kind = %s AND key = %s",
                         (unit.kind, unit.key))

    def get(self, unit: Unit) -> Card | None:
        """One unit's card, or None when it has none — a word marked known
        has had its card removed, and a word the roadmap never reached never
        had one."""
        with open_state(self._db) as conn:
            row = conn.execute(
                "SELECT card_id, kind, key, due_date, interval_days, ease_factor,"
                " repetitions, last_review, lapses FROM cards WHERE kind = %s AND key = %s",
                (unit.kind, unit.key),
            ).fetchone()
        return self._from_row(row) if row else None

    def due(self, now: datetime, limit: int = 20) -> list[Card]:
        # Ties broken by `card_id`, the order the cards were made in: a
        # roadmap mints its cards together, so a hundred share a due date,
        # and Postgres -- unlike SQLite, reading by rowid -- returns ties in
        # whatever order the table holds them, which an update reshuffles.
        with open_state(self._db) as conn:
            rows = conn.execute(
                "SELECT card_id, kind, key, due_date, interval_days, ease_factor,"
                " repetitions, last_review, lapses FROM cards WHERE due_date <= %s"
                " ORDER BY due_date, card_id LIMIT %s",
                (now.isoformat(), limit),
            ).fetchall()
        return [self._from_row(row) for row in rows]

    def all(self) -> list[Card]:
        """Every card, for the rule that reads encounters against them."""
        with open_state(self._db) as conn:
            rows = conn.execute(
                "SELECT card_id, kind, key, due_date, interval_days, ease_factor,"
                " repetitions, last_review, lapses FROM cards"
                " ORDER BY due_date, card_id").fetchall()
        return [self._from_row(row) for row in rows]

    def counts(self, now: datetime) -> tuple[int, int]:
        """(total cards, cards due now)."""
        with open_state(self._db) as conn:
            total = conn.execute("SELECT count(*) FROM cards").fetchone()[0]
            due = conn.execute(
                "SELECT count(*) FROM cards WHERE due_date <= %s", (now.isoformat(),)
            ).fetchone()[0]
        return total, due

    @staticmethod
    def _to_row(card: Card) -> tuple:
        return (
            card.unit.kind, card.unit.key, card.due_date.isoformat(),
            card.interval_days, card.ease_factor, card.repetitions,
            card.last_review.isoformat() if card.last_review else None,
            card.lapses,
        )

    @staticmethod
    def _from_row(row: tuple) -> Card:
        card_id, kind, key, due, interval, ease, reps, last, lapses = row
        return Card(
            unit=Unit(kind, key),
            due_date=datetime.fromisoformat(due),
            interval_days=interval,
            ease_factor=ease,
            repetitions=reps,
            last_review=datetime.fromisoformat(last) if last else None,
            lapses=lapses,
            card_id=card_id,
        )
